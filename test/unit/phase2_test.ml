let hard_link_mode_preservation () =
  let inode path = (Unix.stat path).st_ino in
  let mode path = (Unix.stat path).st_perm in
  let transaction_directories root =
    let transactions = Filename.concat root ".clamp/transactions" in
    if Sys.file_exists transactions then
      Sys.readdir transactions |> Array.to_list
      |> List.map (Filename.concat transactions)
    else []
  in
  let active_transaction root =
    match transaction_directories root with
    | [ transaction ] -> transaction
    | _ -> Alcotest.fail "expected exactly one active transaction"
  in
  let assert_no_transactions root =
    Alcotest.(check (list string)) "transaction namespace is empty" []
      (transaction_directories root)
  in
  let transaction_has_contents root expected =
    let rec search path =
      Sys.readdir path |> Array.to_list
      |> List.exists (fun name ->
             let child = Filename.concat path name in
             match (Unix.lstat child).st_kind with
             | Unix.S_DIR -> search child
             | Unix.S_REG -> read child = expected
             | _ -> false)
    in
    List.exists search (transaction_directories root)
  in
  let prepare root id =
    ignore
      (get_ok
         (Clamp.Local.mutate ~repo:root ~id
            ~contents:(fact ~body:"Old hard-linked bytes." ()) ~claim:"explicit"
            ~confirmed:false ~allow_unknown:false ~create:true));
    let target = Filename.concat root ("knowledge/" ^ id ^ ".md") in
    let alias = target ^ ".alias" in
    Unix.link target alias;
    Unix.chmod target 0o6755;
    (target, alias, read target, inode target)
  in
  with_bundle (fun root ->
      let target, alias, old, old_inode = prepare root "facts/hard-link-rollback" in
      let result =
        Clamp.Local.For_test.with_ownership_hook
          (fun phase ->
            if phase = Clamp.Local.After_target_exchange then
              failwith "force hard-link rollback")
          (fun () ->
            Clamp.Local.mutate ~repo:root ~id:"facts/hard-link-rollback"
              ~contents:(fact ~body:"Requested replacement." ()) ~claim:"explicit"
              ~confirmed:false ~allow_unknown:false ~create:false)
      in
      Alcotest.(check string) "forced hard-link edit rolls back" "write_failed"
        (error_code result);
      Alcotest.(check string) "rollback target exact old bytes" old (read target);
      Alcotest.(check string) "rollback alias exact old bytes" old (read alias);
      Alcotest.(check int) "rollback target keeps original inode" old_inode
        (inode target);
      Alcotest.(check int) "rollback alias remains linked" old_inode (inode alias);
      Alcotest.(check int) "rollback target preserves full mode" 0o6755
        (mode target);
      Alcotest.(check int) "rollback alias preserves full mode" 0o6755 (mode alias);
      Alcotest.(check int) "rollback preserves two hard links" 2
        (Unix.stat target).st_nlink;
      assert_no_transactions root);
  with_bundle (fun root ->
      let _, alias, _, _ = prepare root "facts/hard-link-mode-race" in
      let result =
        Clamp.Local.For_test.with_ownership_hook
          (fun phase ->
            if phase = Clamp.Local.After_target_exchange then begin
              Unix.chmod alias 0o755;
