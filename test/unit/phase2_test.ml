        Alcotest.(check bool) "selected receipt window was reached" true !fired;
        Alcotest.(check string) "post-receipt leaf replacement is uncertain"
          "rollback_state_uncertain" (error_code result);
        Alcotest.(check string) "foreign leaf remains public" marker (read selected);
        Alcotest.(check bool) "requested leaf remains preserved" true
          (Sys.file_exists displaced);
        ())
  in
  List.iter run cases

