let with_failed_operation failures action =
  let counts = Hashtbl.create 8 in
  let result =
    Clamp.Local.For_test.with_operation_hook
      (fun operation ->
        let count = Option.value (Hashtbl.find_opt counts operation) ~default:0 + 1 in
        Hashtbl.replace counts operation count;
        if List.mem (operation, count) failures then
          failwith "injected operation failure")
      action
  in
  List.iter
    (fun (operation, occurrence) ->
      let observed = Option.value (Hashtbl.find_opt counts operation) ~default:0 in
      Alcotest.(check bool) "configured failure occurrence was reached" true
        (observed >= occurrence))
    failures;
  result

