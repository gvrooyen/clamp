let todo_validation_edges () =
  with_bundle (fun root ->
      let codes () =
        (Clamp.Bundle.validate root).diagnostics
        |> List.map (fun diagnostic -> diagnostic.Clamp.Diagnostic.code)
      in
      Alcotest.(check bool) "empty missing TODO drifts" true
        (List.mem "todo_drift" (codes ()));
      ignore (get_ok (Clamp.Local.todo root));
      Alcotest.(check bool) "empty TODO repairs" false
        (List.mem "todo_drift" (codes ()));
      Sys.remove (Filename.concat root "TODO.md");
      Unix.symlink "/tmp/not-a-todo" (Filename.concat root "TODO.md");
      Alcotest.(check bool) "TODO symlink is diagnosed" true
        (List.mem "todo_unreadable" (codes ())));
  let check_uncertain label = function
    | Error (issue : Clamp.Local.error) ->
        Alcotest.(check string) label "rollback_state_uncertain" issue.code;
        Alcotest.(check string) (label ^ " body-free")
          "Could not verify local state after a failed mutation." issue.message
    | Ok _ -> Alcotest.fail (label ^ ": expected uncertainty")
  in
  List.iter
    (fun selected ->
      with_bundle (fun root ->
          ignore (get_ok (Clamp.Local.todo root));
          let path = Filename.concat root "TODO.md" in
          let bytes = read path and fired = ref false in
          let mode =
            match selected with
            | Clamp.Local.After_todo_inspect -> 0o640
            | Clamp.Local.After_todo_opened -> 0o604
          in
          let result =
            Clamp.Local.For_test.with_optional_todo_read_hook
              (fun phase ->
                if phase = selected then begin
                  fired := true;
                  (match phase with
                  | Clamp.Local.After_todo_inspect ->
                      Unix.rename path (path ^ ".moved");
                      write path "foreign replacement TODO\n";
                      Unix.chmod path mode
                  | Clamp.Local.After_todo_opened -> Unix.chmod path mode)
                end)
              (fun () -> Clamp.Local.todo_drift root)
          in
          Alcotest.(check bool) "TODO race hook fired" true !fired;
          check_uncertain "TODO witness race" result;
          Alcotest.(check string) "TODO race preserves bytes" bytes
            (read
               (if selected = Clamp.Local.After_todo_inspect then path ^ ".moved"
                else path));
          if selected = Clamp.Local.After_todo_inspect then
            Alcotest.(check string) "TODO replacement evidence survives"
              "foreign replacement TODO\n" (read path);
          Alcotest.(check int) "TODO race preserves foreign mode" mode
            (Unix.stat path).st_perm))
    [ Clamp.Local.After_todo_inspect; Clamp.Local.After_todo_opened ];
  with_bundle (fun root ->
      ignore (get_ok (Clamp.Local.todo root));
      let path = Filename.concat root "TODO.md" in
      let moved = path ^ ".disappeared" and fired = ref false in
      let result =
        Clamp.Local.For_test.with_optional_todo_read_hook
          (fun phase ->
            if phase = Clamp.Local.After_todo_inspect then begin
              fired := true;
              Unix.rename path moved
            end)
          (fun () -> Clamp.Local.todo_drift root)
      in
      Alcotest.(check bool) "TODO disappearance hook fired" true !fired;
      check_uncertain "TODO post-inspect disappearance" result;
      Alcotest.(check bool) "disappeared TODO evidence retained" true
        (Sys.file_exists moved);
