let process_root_flock () =
  with_bundle (fun root ->
      let locked_r, locked_w = Unix.pipe ~cloexec:true () in
      match Unix.fork () with
      | 0 ->
          Unix.close locked_r;
          let descriptor = Clamp.Secure_fs.open_directory root in
          Clamp.Secure_fs.flock descriptor true;
          ignore (Unix.write_substring locked_w "1" 0 1);
          Unix.sleepf 0.25;
          Clamp.Secure_fs.funlock descriptor;
          Unix.close descriptor;
          exit 0
      | pid ->
          Unix.close locked_w;
          let byte = Bytes.create 1 in
          ignore (Unix.read locked_r byte 0 1);
          write (Filename.concat root ".clamp.lock") "replaceable legacy path\n";
          let descriptor = Clamp.Secure_fs.open_directory root in
          let started = Unix.gettimeofday () in
          Clamp.Secure_fs.flock descriptor false;
          let waited = Unix.gettimeofday () -. started in
          Clamp.Secure_fs.funlock descriptor;
          Unix.close descriptor;
          ignore (Unix.waitpid [] pid);
          Unix.close locked_r;
          Alcotest.(check bool) "shared lock waited for root exclusive lock" true
            (waited >= 0.15))

