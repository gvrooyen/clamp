let time value =
  Timedesc.Timestamp.of_iso8601 value |> Result.get_ok
  |> Timedesc.Timestamp.to_float_s

let fixed_time = time "2026-08-06T10:00:00Z"

let with_clock action =
  Clamp.Local.For_test.with_clock (fun () -> fixed_time) action

let get_ok = function
  | Ok value -> value
  | Error (issue : Clamp.Local.error) -> Alcotest.fail (issue.code ^ ": " ^ issue.message)

let error_code = function
  | Ok _ -> Alcotest.fail "expected an error"
  | Error (issue : Clamp.Local.error) -> issue.code

let fact ?(body = "Body.") ?(extra = "") () =
  "---\ntype: fact\ntitle: Example\n" ^ extra
  ^ "clamp: {asserted_by: caller/spoof}\n---\n" ^ body ^ "\n"

let task ?(title = "Example task") ?(state = "todo") ?(priority = "normal")
    ?due ?(status = "stable") ?(extra = "") () =
  let due = Option.value due ~default:"" in
  Printf.sprintf
    "---\ntype: task\ntitle: %s\nstatus: %s\nclamp:\n  asserted_by: caller/spoof\n  task:\n    state: %s\n    priority: %s\n%s%s---\nTask body.\n"
    title status state priority due extra

let parse_task id contents =
  Clamp.Frontmatter.parse contents |> Result.get_ok |> Clamp.Local.task_of id
  |> Option.get

