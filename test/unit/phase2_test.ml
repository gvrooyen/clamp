    (try ignore (index "Blocked](knowledge" ); ignore (index "OVERDUE"); true with Not_found -> false);
  Alcotest.(check bool) "closed task omitted" false
    (try ignore (index "Done"); true with Not_found -> false)

let ulid_contract () =
  let zero count = Bytes.make count '\000' in
  let low = Clamp.Local.ulid_with ~now_ms:(fun () -> 0L) ~entropy:zero in
  let max =
    Clamp.Local.ulid_with ~now_ms:(fun () -> 281474976710655L)
      ~entropy:(fun count -> Bytes.make count '\255')
  in
  Alcotest.(check string) "zero vector" "00000000000000000000000000" low;
  Alcotest.(check bool) "valid max" true (Clamp.Local.valid_ulid max);
  Alcotest.(check char) "max timestamp prefix" '7' max.[0];
  let earlier = Clamp.Local.ulid_with ~now_ms:(fun () -> 1000L) ~entropy:zero in
  let later = Clamp.Local.ulid_with ~now_ms:(fun () -> 1001L) ~entropy:zero in
  Alcotest.(check bool) "timestamp prefix orders different milliseconds" true
    (String.compare earlier later < 0);
  let generated = List.init 2_000 (fun _ -> Clamp.Local.ulid ()) in
  Alcotest.(check int) "collision resistance" 2_000
    (List.length (List.sort_uniq String.compare generated));
  Alcotest.check_raises "short entropy rejected"
    (Invalid_argument "ULID entropy must be exactly 80 bits") (fun () ->
      ignore
        (Clamp.Local.ulid_with ~now_ms:(fun () -> 0L)
           ~entropy:(fun _ -> Bytes.create 9)));
  let boundary = String.make 47 'a' ^ " b" |> Clamp.Local.slug in
  Alcotest.(check bool) "long slug remains valid" true
    (Clamp.Local.valid_slug boundary);
  Alcotest.(check bool) "long slug has no trailing dash" false
    (String.ends_with ~suffix:"-" boundary)

