let has_clamp_temp root =
  let rec walk path =
    Sys.readdir path
    |> Array.exists (fun name ->
           let child = Filename.concat path name in
           String.starts_with ~prefix:".clamp-" name
           && String.ends_with ~suffix:".tmp" name
           || (Unix.lstat child).st_kind = Unix.S_DIR && walk child)
  in
  walk root

let assert_clean_failure root =
  Alcotest.(check bool) "no obsolete temporary files remain" false
    (has_clamp_temp root);
  let transactions = Filename.concat root ".clamp/transactions" in
  let count =
    if Sys.file_exists transactions then Array.length (Sys.readdir transactions)
    else 0
  in
  Alcotest.(check int) "no active private transaction remains" 0 count

let assert_uncertain_transaction root =
  let transactions = Filename.concat root ".clamp/transactions" in
  Alcotest.(check bool) "private transaction namespace exists" true
    (Sys.file_exists transactions);
  let names = Sys.readdir transactions in
  Alcotest.(check bool) "uncertain transaction remains" true
    (Array.length names > 0);
  let contains_entry =
    Array.exists
      (fun name ->
        let path = Filename.concat transactions name in
        (Unix.lstat path).st_kind = Unix.S_DIR
        && Array.length (Sys.readdir path) > 0)
      names
  in
  Alcotest.(check bool) "uncertain transaction retains private state" true
    contains_entry

let active_transaction_directory root =
  let transactions = Filename.concat root ".clamp/transactions" in
  let names = Sys.readdir transactions |> Array.to_list in
  match names with
  | [ name ] -> Filename.concat transactions name
  | _ -> Alcotest.fail "expected exactly one active private transaction"

let assert_transactions_empty root =
  let transactions = Filename.concat root ".clamp/transactions" in
  let count =
    if Sys.file_exists transactions then Array.length (Sys.readdir transactions)
    else 0
  in
  Alcotest.(check int) "completed operation removes transaction" 0 count

let transaction_evidence_retained root =
  let transactions = Filename.concat root ".clamp/transactions" in
  Sys.file_exists transactions && Array.length (Sys.readdir transactions) > 0

let transaction_contains_contents root expected =
  let rec search path =
    Sys.readdir path
    |> Array.exists (fun name ->
           let child = Filename.concat path name in
           match (Unix.lstat child).st_kind with
           | Unix.S_DIR -> search child
           | Unix.S_REG -> read child = expected
           | _ -> false)
  in
  let transactions = Filename.concat root ".clamp/transactions" in
  Sys.file_exists transactions && search transactions

let standalone_restoration_matrix () =
  let cases =
    [ [ (Clamp.Local.Temp_create, 1) ]; [ (Clamp.Local.Write, 1) ];
      [ (Clamp.Local.File_fsync, 1) ]; [ (Clamp.Local.Rename, 1) ];
      [ (Clamp.Local.Dir_fsync, 1) ];
      [ (Clamp.Local.Write, 1); (Clamp.Local.Unlink, 1) ] ]
  in
  List.iteri
    (fun case_index failures ->
      with_bundle (fun root ->
          ignore
            (get_ok
               (Clamp.Local.mutate ~repo:root ~id:"facts/recovery"
                  ~contents:(fact ~body:"Old." ()) ~claim:"explicit"
                  ~confirmed:false ~allow_unknown:false ~create:true));
          let path = Filename.concat root "knowledge/facts/recovery.md" in
          let old = read path in
          let result =
            with_failed_operation failures (fun () ->
                Clamp.Local.mutate ~repo:root ~id:"facts/recovery"
                  ~contents:(fact ~body:"Requested." ()) ~claim:"explicit"
                  ~confirmed:false ~allow_unknown:false ~create:false)
          in
          Alcotest.(check string)
            (Printf.sprintf "verified recovery reports write failure case %d" case_index)
            "write_failed" (error_code result);
          Alcotest.(check string) "standalone snapshot restored" old (read path);
          assert_clean_failure root))
    cases;
  with_bundle (fun root ->
      ignore
        (get_ok
           (Clamp.Local.mutate ~repo:root ~id:"facts/uncertain"
              ~contents:(fact ~body:"Old." ()) ~claim:"explicit"
              ~confirmed:false ~allow_unknown:false ~create:true));
      let counts = Hashtbl.create 8 and active = ref false in
      let result =
        Clamp.Local.For_test.with_ownership_hook
          (fun phase ->
            if phase = Clamp.Local.Before_target_install then active := true)
          (fun () ->
            Clamp.Local.For_test.with_operation_hook
              (fun operation ->
                if !active then begin
                  let count =
                    Option.value (Hashtbl.find_opt counts operation) ~default:0 + 1
