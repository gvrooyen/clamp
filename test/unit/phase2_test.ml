        let selected = match leaf with `Task -> task_path | `Todo -> todo_path in
        let displaced = selected ^ ".requested" in
        let cleanup_count = ref 0 and fired = ref false in
        let marker =
          match leaf with
          | `Task -> "foreign task leaf\n"
          | `Todo -> "foreign TODO leaf\n"
        in
