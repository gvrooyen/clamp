let canonical_status_policy () =
  let with_status status contents =
    Str.replace_first (Str.regexp_string "clamp:")
      ("status: " ^ status ^ "\nclamp:") contents
  in
  let status path =
    let document = Clamp.Frontmatter.parse (read path) |> Result.get_ok in
    Option.bind (Clamp.Exact_yaml.find "status" document.metadata)
      Clamp.Exact_yaml.string
    |> Option.value ~default:"stable"
  in
  let verification path =
    let document = Clamp.Frontmatter.parse (read path) |> Result.get_ok in
    Clamp.Local.verification_events document.metadata
  in
  let metadata_value path key =
    let document = Clamp.Frontmatter.parse (read path) |> Result.get_ok in
    Clamp.Exact_yaml.find key document.metadata
  in
  let clamp_value path key =
    Option.bind (metadata_value path "clamp") (Clamp.Exact_yaml.find key)
  in
  let scalar_value = function
    | Some (Clamp.Exact_yaml.Scalar (_, value)) -> value
    | _ -> ""
  in
  let with_unknown_clamp contents =
    Str.replace_first
      (Str.regexp_string "clamp: {asserted_by: caller/spoof}")
      "clamp:\n  asserted_by: caller/spoof\n  future_provenance:\n    nested:\n      list: [alpha, {deeper: beta}]\n      large_integer: 92233720368547758081234567890\n    multiline: |-\n      first line\n      second line"
      contents
  in
  with_clock (fun () ->
      with_bundle (fun root ->
          let path id = Filename.concat root ("knowledge/" ^ id ^ ".md") in
          let add id contents claim confirmed =
            get_ok
              (Clamp.Local.mutate ~repo:root ~id ~contents ~claim ~confirmed
                 ~allow_unknown:false ~create:true)
            |> ignore
          in
          add "facts/explicit-deprecated"
            (with_status "deprecated" (fact ())) "explicit" false;
