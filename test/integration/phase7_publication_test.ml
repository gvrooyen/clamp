let clean_races_and_recovery () =
  with_environment "one-race" (fun env ->
      local_change env "race-local";
      let refs = ref [] in
      let hooks =
        { Clamp.Publication.For_test.before_push =
            (fun ~attempt ~refspec ->
              refs := refspec :: !refs;
              if attempt = 1 then ignore (advance_writer env 1 ()));
          after_preservation_proven = (fun ~branch:_ ~commit:_ -> ());
          after_main_push = (fun ~commit:_ -> ());
          before_sync = (fun ~commit:_ -> ()); now = (fun () -> 1_787_733_723.) }
      in
      ignore (check_ok "one race" (run ~hooks env));
      Alcotest.(check int) "two main pushes" 2 (List.length !refs);
      List.iter
        (fun refspec ->
          Alcotest.(check bool) "no force refspec" false
            (String.starts_with ~prefix:"+" refspec
             || String.contains refspec ' '))
        !refs);
  with_environment "three-races" (fun env ->
      local_change env "pending";
      let main_attempts = ref 0 and observed = ref [] in
      let hooks =
        { Clamp.Publication.For_test.before_push =
            (fun ~attempt ~refspec ->
              observed := (attempt, refspec) :: !observed;
              if attempt <= 3 then begin
                incr main_attempts;
                ignore (advance_writer env attempt ())
              end);
          after_preservation_proven = (fun ~branch:_ ~commit:_ -> ());
          after_main_push = (fun ~commit:_ -> ());
          before_sync = (fun ~commit:_ -> Alcotest.fail "race exhaustion synced");
          now = (fun () -> 1_787_733_723.) }
      in
      let error = check_error "race exhaustion" "publish_race_exhausted"
          (run ~hooks env) in
      Alcotest.(check int) "exactly three races" 3 !main_attempts;
      let branch = Option.get error.branch and commit = Option.get error.commit in
      Alcotest.(check string) "recovery ref commit" commit
        (git_output env.bare [ "rev-parse"; "refs/heads/" ^ branch ]);
      ignore (git_output env.bare
                [ "show"; commit ^ ":knowledge/facts/pending.md" ]);
      for index = 1 to 3 do
        ignore (git_output env.bare
                  [ "show";
                    Printf.sprintf "%s:knowledge/facts/winner-%d.md" commit index ])
      done;
      let main = git_output env.bare [ "rev-parse"; "refs/heads/main" ] in
      let missing =
        not (git_succeeds env.bare
               [ "cat-file"; "-e"; main ^ ":knowledge/facts/pending.md" ])
      in
      Alcotest.(check bool) "pending absent from main" true missing;
      List.iter
        (fun (_, refspec) ->
          Alcotest.(check bool) "no force path" false
            (String.starts_with ~prefix:"+" refspec
             || String.contains refspec ' '))
        !observed;
      Alcotest.(check string) "recovery terminal state cleaned" ""
        (publication_refs env))

