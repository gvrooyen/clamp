let cli_contract () =
  with_environment "cli-json" (fun env ->
      local_change env "cli";
      let status, output, errors =
        capture_cli
          [ "publish"; "--repo"; env.clone; "--thread-id"; thread_id;
            "--json" ]
      in
      Alcotest.(check bool) "stale exit 6" true (status = Unix.WEXITED 6);
      Alcotest.(check string) "JSON stderr" "" errors;
      let json = Yojson.Safe.from_string output in
      let open Yojson.Safe.Util in
      Alcotest.(check string) "stale code" "publish_complete_index_stale"
        (json |> member "code" |> to_string);
      Alcotest.(check bool) "published true" true
        (json |> member "details" |> member "published" |> to_bool);
      let commit = json |> member "details" |> member "commit" |> to_string in
      Alcotest.(check string) "CLI exact durable SHA" commit
        (git_output env.bare [ "rev-parse"; "refs/heads/main" ]));
  with_environment "cli-human" (fun env ->
      local_change env "cli-human";
      let status, output, errors =
        capture_cli
          [ "publish"; "--repo"; env.clone; "--thread-id"; thread_id ]
      in
      Alcotest.(check bool) "human stale exit 6" true (status = Unix.WEXITED 6);
      Alcotest.(check string) "human stdout" "" output;
      Alcotest.(check string) "human stale message"
        "kb: Git publication succeeded, but the derived index is stale and must be synchronized later.\n"
        errors);
  with_environment "cli-conflict" (fun env ->
      let sentinel = "KNOWLEDGE_BODY_SECRET_SENTINEL" in
      write (Filename.concat env.clone "knowledge/facts/same.md")
        (fact "Same" sentinel);
      write (Filename.concat env.writer "knowledge/facts/same.md")
        (fact "Same" "Remote version.");
      ignore (commit_writer env "remote conflict");
      let status, output, errors =
        capture_cli
          [ "publish"; "--repo"; env.clone; "--thread-id"; thread_id;
            "--json" ]
      in
      Alcotest.(check bool) "conflict exit 3" true (status = Unix.WEXITED 3);
      Alcotest.(check string) "conflict stderr" "" errors;
      Alcotest.(check bool) "knowledge body absent" false
        (contains output sentinel);
      let json = Yojson.Safe.from_string output in
      let open Yojson.Safe.Util in
      Alcotest.(check string) "conflict code" "publish_conflict"
        (json |> member "code" |> to_string);
      Alcotest.(check (list string)) "body-free conflict paths"
        [ "knowledge/facts/same.md" ]
        (json |> member "details" |> member "paths" |> to_list
         |> List.map to_string))

