let capture_binary binary arguments =
  let output_path = Filename.temp_file "clamp-p7-cli" ".out"
  and error_path = Filename.temp_file "clamp-p7-cli" ".err" in
  let output = Unix.openfile output_path [ Unix.O_WRONLY; Unix.O_TRUNC ] 0o600
  and errors = Unix.openfile error_path [ Unix.O_WRONLY; Unix.O_TRUNC ] 0o600 in
  let environment =
    [| "PATH=/usr/bin:/bin"; "HOME=/nonexistent"; "LC_ALL=C"; "LANG=C" |]
  in
  let argv = Array.of_list (binary :: arguments) in
  let pid =
    Unix.create_process_env binary argv environment Unix.stdin output errors
  in
  Unix.close output; Unix.close errors;
  let _, status = Unix.waitpid [] pid in
  let stdout = read output_path and stderr = read error_path in
  Sys.remove output_path; Sys.remove error_path;
  (status, stdout, stderr)

let capture_cli arguments =
  let binary =
    if Sys.file_exists "_build/default/bin/kb.exe" then
      "_build/default/bin/kb.exe"
    else "../../bin/kb.exe"
  in
  capture_binary binary arguments

let check_ok label = function
  | Ok (report : Clamp.Publication.report) -> report
  | Error (error : Clamp.Publication.error) ->
      Alcotest.failf "%s: %s (%s)" label error.message error.code

let check_error label code = function
  | Ok _ -> Alcotest.failf "%s: expected %s" label code
  | Error (error : Clamp.Publication.error) ->
      Alcotest.(check string) label code error.code;
      error

