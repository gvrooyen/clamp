let v3_body_to_v1 body =
  match String.split_on_char '\000' body with
  | "clamp-publish-state-v3" :: races
    :: ("none" | "legacy_unresolved") :: "" :: rest ->
      Some (String.concat "\000" ("clamp-publish-state-v1" :: races :: rest))
  | _ -> None

let downgrade_publication_state_to_v1 env =
  let old_object = git_output env.clone [ "rev-parse"; publication_state_ref ] in
  let v3_body = publication_state_body env in
  let v1_body =
    match v3_body_to_v1 v3_body with
    | Some body -> body
    | None ->
        Alcotest.fail
          "only unallocated not-started or legacy v3 state can be downgraded to v1"
  in
  let body_path = Filename.concat env.root "publication-state-v1.bin" in
  write body_path v1_body;
  let v1_object =
    git_output env.clone [ "hash-object"; "-w"; "--"; body_path ]
  in
  git env.clone
    [ "update-ref"; publication_state_ref; v1_object; old_object ];
  Alcotest.(check string) "installed exact v1 state body" v1_body
    (publication_state_body env);
  v1_body, v1_object

let check_v1_migrated_exactly label env v1_body =
  let v3_body = publication_state_body env in
  Alcotest.(check bool) (label ^ " has v3 magic") true
    (String.starts_with ~prefix:"clamp-publish-state-v3\000" v3_body);
  let reconstructed = v3_body_to_v1 v3_body in
  Alcotest.(check (option string)) (label ^ " preserves every v1 field")
    (Some v1_body) reconstructed

let v3_body_to_v2 body =
  match String.split_on_char '\000' body with
  | "clamp-publish-state-v3" :: races :: status :: branch :: rest
    when List.mem status
           [ "none"; "legacy_unresolved"; "push_pending"; "proven" ] ->
      Some
        (String.concat "\000"
           ("clamp-publish-state-v2" :: races :: branch :: rest))
  | _ -> None

let downgrade_publication_state_to_v2 env =
  let old_object = git_output env.clone [ "rev-parse"; publication_state_ref ] in
  let v2_body =
    match v3_body_to_v2 (publication_state_body env) with
    | Some body -> body
    | None -> Alcotest.fail "current publication state cannot be encoded as v2"
  in
  let body_path = Filename.concat env.root "publication-state-v2.bin" in
  write body_path v2_body;
  let v2_object =
    git_output env.clone [ "hash-object"; "-w"; "--"; body_path ]
  in
  git env.clone
    [ "update-ref"; publication_state_ref; v2_object; old_object ];
  v2_body, v2_object

let clean_and_outdated () =
  with_environment "clean" (fun env ->
      Alcotest.(check string) "shallow clone" "true"
        (git_output env.clone [ "rev-parse"; "--is-shallow-repository" ]);
      local_change env "clean";
      let synced = ref None in
      let report =
        check_ok "clean publish"
          (run ~sync:(fun commit -> synced := Some commit; successful_sync commit) env)
      in
      Alcotest.(check string) "remote exact commit" report.commit
        (git_output env.bare [ "rev-parse"; "refs/heads/main" ]);
      Alcotest.(check (option string)) "exact SHA passed to sync"
        (Some report.commit) !synced);
  with_environment "outdated" (fun env ->
      local_change env "local";
      ignore (advance_writer env 1 ());
      let report = check_ok "outdated publish" (run env) in
      ignore (git_output env.bare
                [ "show"; report.commit ^ ":knowledge/facts/local.md" ]);
      ignore (git_output env.bare
                [ "show"; report.commit ^ ":knowledge/facts/winner-1.md" ]));
  with_environment "known-outdated" (fun env ->
      ignore (advance_writer env 2 ());
      git env.clone [ "fetch"; "--quiet"; "origin"; "main" ];
      let head = git_output env.clone [ "rev-parse"; "HEAD" ]
      and tracked =
        git_output env.clone [ "rev-parse"; "refs/remotes/origin/main" ]
      in
      Alcotest.(check bool) "local main is strictly behind tracking" true
        (head <> tracked
         && git_succeeds env.clone
              [ "merge-base"; "--is-ancestor"; head; tracked ]);
      local_change env "known-behind-local";
      let synced = ref None in
      let report =
        check_ok "known-behind publish"
          (run ~sync:(fun commit -> synced := Some commit; successful_sync commit)
             env)
      in
      Alcotest.(check string) "known-behind exact remote result" report.commit
        (git_output env.bare [ "rev-parse"; "refs/heads/main" ]);
      Alcotest.(check string) "known-behind exact sync result" "sync_complete"
        (Clamp.Sync.completion_code report.sync);
      Alcotest.(check (option string)) "known-behind exact sync SHA"
        (Some report.commit) !synced;
      ignore
        (git_output env.bare
           [ "show"; report.commit ^ ":knowledge/facts/winner-2.md" ]);
      ignore
        (git_output env.bare
           [ "show";
             report.commit ^ ":knowledge/facts/known-behind-local.md" ]);
      Alcotest.(check string) "known-behind terminal state cleaned" ""
        (publication_refs env))

