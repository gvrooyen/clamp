let command program arguments =
  let argv = Array.of_list (program :: arguments) in
  let null = Unix.openfile "/dev/null" [ Unix.O_RDWR ] 0 in
  let pid = Unix.create_process program argv Unix.stdin null null in
  let _, status = Unix.waitpid [] pid in
  Unix.close null;
  match status with
  | Unix.WEXITED 0 -> ()
  | _ -> Alcotest.failf "%s failed" program

let git repo arguments = command "/usr/bin/git" ("-C" :: repo :: arguments)

let git_succeeds repo arguments =
  let argv = Array.of_list ("git" :: "-C" :: repo :: arguments) in
  let null = Unix.openfile "/dev/null" [ Unix.O_RDWR ] 0 in
  let pid = Unix.create_process "/usr/bin/git" argv Unix.stdin null null in
  let _, status = Unix.waitpid [] pid in
  Unix.close null;
  status = Unix.WEXITED 0

let contains text fragment =
  try ignore (Str.search_forward (Str.regexp_string fragment) text 0); true
  with Not_found -> false

let git_output_raw repo arguments =
  let input, output = Unix.pipe ~cloexec:true () in
  let argv = Array.of_list ("git" :: "-C" :: repo :: arguments) in
  let pid = Unix.create_process "/usr/bin/git" argv Unix.stdin output Unix.stderr in
  Unix.close output;
  let channel = Unix.in_channel_of_descr input in
  let text =
    Fun.protect ~finally:(fun () -> close_in_noerr channel) (fun () ->
        let buffer = Buffer.create 128 in
        (try while true do Buffer.add_channel buffer channel 4096 done
         with End_of_file -> ());
        Buffer.contents buffer)
  in
  match snd (Unix.waitpid [] pid) with
  | Unix.WEXITED 0 -> text
  | _ -> Alcotest.fail "git output command failed"

let git_output repo arguments = String.trim (git_output_raw repo arguments)

let rec remove path =
  try
    match (Unix.lstat path).st_kind with
    | Unix.S_DIR ->
        Sys.readdir path
        |> Array.iter (fun name -> remove (Filename.concat path name));
        Unix.rmdir path
    | _ -> Unix.unlink path
  with Unix.Unix_error (Unix.ENOENT, _, _) -> ()

let mkdir_p path =
  let rec create current =
    if current <> Filename.dirname current && not (Sys.file_exists current)
    then begin create (Filename.dirname current); Unix.mkdir current 0o700 end
  in
  create path

let write path contents =
  mkdir_p (Filename.dirname path);
  let channel = open_out_bin path in
  Fun.protect ~finally:(fun () -> close_out channel) (fun () ->
      output_string channel contents)

let read path =
  let channel = open_in_bin path in
  Fun.protect ~finally:(fun () -> close_in channel) (fun () ->
      really_input_string channel (in_channel_length channel))

