  and writer = Filename.concat root "writer"
  and clone = Filename.concat root "clone" in
  command "/usr/bin/git"
    [ "init"; "--quiet"; "--bare"; "--initial-branch=main"; bare ];
  command "/usr/bin/git"
    [ "init"; "--quiet"; "--initial-branch=main"; writer ];
  git writer [ "config"; "user.name"; "Clamp Writer" ];
  git writer [ "config"; "user.email"; "writer@local.invalid" ];
  git writer [ "remote"; "add"; "origin"; bare ];
