let commit_writer env message =
  git env.writer [ "add"; "-A" ];
  git env.writer [ "commit"; "--quiet"; "-m"; message ];
  git env.writer [ "push"; "--quiet"; "origin"; "main" ];
  git_output env.writer [ "rev-parse"; "HEAD" ]

let advance_writer env index ?(same = false) () =
  git env.writer [ "fetch"; "--quiet"; "origin"; "main" ];
  git env.writer [ "reset"; "--quiet"; "--hard"; "origin/main" ];
  let path =
    if same then "knowledge/facts/same.md"
    else Printf.sprintf "knowledge/facts/winner-%d.md" index
  in
  write (Filename.concat env.writer path)
    (fact (Printf.sprintf "Winner %d" index)
       (Printf.sprintf "Remote winner %d." index));
  commit_writer env (Printf.sprintf "writer %d" index)

