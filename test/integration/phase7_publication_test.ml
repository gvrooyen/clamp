        check_error "published cleanup failure" "publish_complete_cleanup_failed"
          (run ~hooks env)
      in
      Alcotest.(check bool) "cleanup failure remains published" true
        error.published;
      Alcotest.(check (option string)) "cleanup exact published SHA" !pushed
        error.commit;
      Alcotest.(check string) "cleanup-failed main is durable"
        (Option.get !pushed)
        (git_output env.bare [ "rev-parse"; "refs/heads/main" ]);
      Alcotest.(check bool) "failed cleanup not ignored" true
        (publication_refs env <> "");
      git env.clone
        [ "update-ref"; "-d";
          "refs/clamp/publish/" ^ thread_id ^ "/state" ]);
  with_environment "cleanup-and-sync-failure" (fun env ->
      local_change env "combined-failure";
      let pushed = ref None in
      let state_directory =
        Filename.concat env.clone
          (".git/refs/clamp/publish/" ^ thread_id)
      in
      let original_mode = ref None in
      let restore_state_directory () =
        Option.iter (Unix.chmod state_directory) !original_mode
      in
      let hooks =
        { Clamp.Publication.For_test.before_push =
            (fun ~attempt:_ ~refspec:_ -> ());
          after_preservation_proven = (fun ~branch:_ ~commit:_ -> ());
          after_main_push =
            (fun ~commit ->
              pushed := Some commit;
              original_mode := Some (Unix.stat state_directory).st_perm;
              Unix.chmod state_directory 0o500);
          before_sync = (fun ~commit:_ -> restore_state_directory ());
          now = Unix.gettimeofday }
      in
      let diagnostic =
        Clamp.Diagnostic.make ~field:"checkpoint" "knowledge"
          "fixture_sync_diagnostic" "Fixture index diagnostic."
      in
      let sync _ =
        Error
          { Clamp.Sync.kind = Transient; code = "fixture_index_failed";
            message = "Index unavailable."; diagnostics = [ diagnostic ] }
      in
      let error =
        Fun.protect ~finally:restore_state_directory (fun () ->
            check_error "combined durable failure"
              "publish_complete_index_stale_cleanup_pending"
              (run ~hooks ~sync env))
      in
      let pushed = Option.get !pushed in
      let message =
        "Git publication succeeded, but the derived index is stale and local publication-state cleanup is incomplete; synchronize the index later and retry or repair local cleanup before another publication."
      in
      Alcotest.(check string) "combined stable message" message error.message;
      Alcotest.(check int) "combined stale exit class" 6
        (Clamp.Publication.exit_class error |> Clamp.Exit_class.code);
      Alcotest.(check bool) "combined result remains published" true
        error.published;
      Alcotest.(check (option string)) "combined exact published SHA"
        (Some pushed) error.commit;
      Alcotest.(check string) "combined main is durable" pushed
        (git_output env.bare [ "rev-parse"; "refs/heads/main" ]);
      Alcotest.(check (option string)) "combined sync cause"
        (Some "fixture_index_failed") error.cause;
      Alcotest.(check (option string)) "combined cleanup cause"
        (Some "publish_state_update_failed") error.cleanup_cause;
      Alcotest.(check bool) "combined refs retained" true
        (publication_refs env <> "");
      let expected_details =
        `Assoc
          [ ("published", `Bool true);
            ("commit", `String pushed);
            ("cause", `String "fixture_index_failed");
            ("cleanup_cause", `String "publish_state_update_failed");
            ("diagnostics", `List [ Clamp.Diagnostic.json diagnostic ]) ]
      in
      Alcotest.(check string) "combined exact JSON details"
        (Yojson.Safe.to_string expected_details)
        (Clamp.Publication.error_details error |> Yojson.Safe.to_string);
      let envelope =
        Clamp.Cli_result.failure
          ~exit_class:(Clamp.Publication.exit_class error) ~code:error.code
          ~message:error.message ~details:(Clamp.Publication.error_details error)
      in
      let expected_envelope =
        `Assoc
          [ ("ok", `Bool false);
            ("code", `String "publish_complete_index_stale_cleanup_pending");
            ("message", `String message);
            ("details", expected_details) ]
      in
      Alcotest.(check string) "combined exact CLI contract"
        (Yojson.Safe.to_string expected_envelope)
        (Clamp.Cli_result.to_yojson envelope |> Yojson.Safe.to_string);
      let recovered = check_ok "retry durable publication cleanup" (run env) in
      Alcotest.(check string) "cleanup retry preserves published SHA" pushed
        recovered.commit;
      Alcotest.(check string) "cleanup retry clears state" ""
        (publication_refs env);
      local_change env "after-cleanup-recovery";
      let next = check_ok "normal publication after cleanup recovery" (run env) in
      Alcotest.(check bool) "later publication advances main" true
        (next.commit <> pushed);
      Alcotest.(check string) "later publication exact remote SHA" next.commit
        (git_output env.bare [ "rev-parse"; "refs/heads/main" ]);
      ignore
        (git_output env.bare
           [ "show";
             next.commit ^ ":knowledge/facts/after-cleanup-recovery.md" ]));
  with_environment "malformed-state" (fun env ->
      local_change env "state-shape";
      let original_ref =
        "refs/clamp/publish/" ^ thread_id ^ "/original"
      in
      git env.clone
        [ "update-ref"; original_ref;
          git_output env.clone [ "rev-parse"; "HEAD" ] ];
      ignore
        (check_error "partial atomic state" "publish_state_invalid" (run env));
      Alcotest.(check bool) "malformed state did not commit pending work" true
        (Sys.file_exists
           (Filename.concat env.clone "knowledge/facts/state-shape.md"));
      git env.clone [ "update-ref"; "-d"; original_ref ])

