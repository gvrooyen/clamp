let user = (Unix.getpwuid (Unix.geteuid ())).pw_name

let connection database =
  let target = Lazy.force target in
  new Postgresql.connection ~host:target.socket_dir
    ~port:(string_of_int target.port) ~dbname:database ~user ()

let sql (connection : Postgresql.connection) statement =
  ignore (connection#exec ~expect:[ Postgresql.Command_ok ] statement)

let scalar (connection : Postgresql.connection) statement =
  let rows = connection#exec ~expect:[ Postgresql.Tuples_ok ] statement in
  rows#getvalue 0 0

let postgres database statement =
  let target = Lazy.force target in
  command "/usr/bin/sudo"
    [ "-u"; "postgres"; "/usr/bin/env"; "-i";
      "HOME=/var/lib/postgresql"; "USER=postgres"; "LOGNAME=postgres";
      "PATH=/usr/bin:/bin"; "PSQLRC=/dev/null"; "/usr/bin/psql";
      "--no-psqlrc"; "--quiet";
      "--set=ON_ERROR_STOP=1"; "--host"; target.socket_dir; "--port";
      string_of_int target.port; "--username"; "postgres"; "--dbname";
      database; "--command"; statement ]

let with_database env operation =
  let database =
    Printf.sprintf "clamp_p8_%d_%d" (Unix.getpid ()) !counter
  in
  let admin = connection "postgres" in
  sql admin ("CREATE DATABASE " ^ quote_identifier database);
  admin#finish;
  postgres database "CREATE EXTENSION vector WITH SCHEMA public";
  let migration_root = Filename.concat env.root "migration-root" in
  List.iter
    (fun name ->
      copy (Filename.concat source_root (Filename.concat "db/migrations" name))
        (Filename.concat migration_root (Filename.concat "db/migrations" name)))
    [ "0001_enable_vector.sql"; "0002_application_schema.sql" ];
  let active = ref None in
  Fun.protect
    ~finally:(fun () ->
      Option.iter
        (fun (connection : Postgresql.connection) ->
          try connection#finish with _ -> ())
        !active;
      postgres "postgres"
        ("DROP DATABASE IF EXISTS " ^ quote_identifier database ^ " WITH (FORCE)");
      remove migration_root)
    (fun () ->
      match Clamp.Database.migrate_local ~repo:migration_root ~database with
      | Error failure -> Alcotest.failf "migration: %s" failure.code
      | Ok _ ->
          let connection = connection database in
          active := Some connection;
          operation connection)

