let conflict_preservation_before_email_request () =
  with_git_environment "conflict-email" (fun env ->
      let local_body = "LOCAL_CONFLICT_BODY_MUST_NOT_BE_EMAILED" in
      write (Filename.concat env.clone "knowledge/facts/initial.md")
        (initial_fact local_body);
      write (Filename.concat env.writer "knowledge/facts/initial.md")
        (initial_fact "Remote conflicting body.");
      ignore (commit_and_push env "remote conflicting update");
      let sync commit =
        Ok
          { Clamp.Sync.commit;
            counts =
              { added = 0; metadata_updated = 0; reembedded = 0;
                unchanged = 0; deleted = 0 };
            rebuilt = false; diagnostics = [] }
      in
      let pending =
        Clamp.Publication.For_test.run ~repo:env.clone ~thread_id
          ~preserve_conflict:false ~sync
          ~hooks:Clamp.Publication.For_test.default_hooks
      in
      let pending =
        match pending with
        | Ok _ -> Alcotest.fail "expected semantic publication conflict"
        | Error failure ->
            Alcotest.(check string) "unpreserved conflict code"
              "publish_conflict" failure.code;
            failure
      in
      let hooks =
        { Clamp.Publication.For_test.default_hooks with
          now = (fun () -> 1_787_832_000.) }
      in
      let preserved =
        Clamp.Publication.For_test.run ~repo:env.clone ~thread_id
          ~preserve_conflict:true ~sync ~hooks
      in
      let preserved =
        match preserved with
        | Ok _ -> Alcotest.fail "preservation returns the conflict exit class"
        | Error failure ->
            Alcotest.(check string) "preserved conflict code"
              "publish_conflict_preserved" failure.code;
            failure
      in
      let branch = Option.get preserved.branch
      and commit = Option.get preserved.commit in
      Alcotest.(check string) "preserved remote ref contains original commit"
        commit (git_output env.bare [ "rev-parse"; "refs/heads/" ^ branch ]);
      Alcotest.(check (list string)) "preserved body-free paths"
        [ "knowledge/facts/initial.md" ] preserved.paths;
      let sent = Hashtbl.create 1 and requests = ref [] in
      let request_email (failure : Clamp.Publication.error) =
        match failure.code, failure.branch, failure.commit with
        | ( ( "publish_conflict_preserved"
            | "publish_conflict_preserved_cleanup_pending" ),
            Some branch, Some commit )
          when failure.preserved ->
            let key = branch ^ "\000" ^ commit in
            if not (Hashtbl.mem sent key) then begin
              Hashtbl.add sent key ();
              let thread_url =
                "https://ampcode.com/threads/" ^ thread_id
              in
              let text =
                String.concat "\n"
                  ([ "Thread: " ^ thread_url; "Conflict ref: " ^ branch;
                     "Preserved commit: " ^ commit; "Paths:" ]
                   @ List.map (fun path -> "- " ^ path) failure.paths)
              in
              requests :=
                `Assoc
                  [ ("operation", `String "new");
                    ( "subject",
                      `String
                        "[Clamp] Knowledge update needs conflict resolution" );
                    ("text", `String text) ]
                :: !requests
            end
        | _ -> ()
      in
      request_email pending;
      Alcotest.(check int) "no request before preservation" 0
        (List.length !requests);
      request_email preserved;
      request_email preserved;
      Alcotest.(check int) "exactly one request after preservation" 1
        (List.length !requests);
      let request = List.hd !requests in
      let open Yojson.Safe.Util in
      Alcotest.(check string) "new owner-email operation" "new"
        (request |> member "operation" |> to_string);
      Alcotest.(check string) "exact owner-email subject"
        "[Clamp] Knowledge update needs conflict resolution"
        (request |> member "subject" |> to_string);
      Alcotest.(check bool) "no recipient field" true
        (request |> member "recipient" = `Null);
      let text = request |> member "text" |> to_string in
