let check_sync label = function
  | Ok report -> report
  | Error (failure : Clamp.Sync.error) ->
      Alcotest.failf "%s: %s (%s)" label failure.message failure.code

let check_retrieval label = function
  | Ok value -> value
  | Error (failure : Clamp.Retrieval.error) ->
      Alcotest.failf "%s: %s (%s)" label failure.message failure.code

let kb_binary () =
  if Sys.file_exists "_build/default/bin/kb.exe" then
    "_build/default/bin/kb.exe"
  else "../../bin/kb.exe"

let capture_kb arguments =
  let output_path = Filename.temp_file "clamp-phase8-kb" ".out"
  and error_path = Filename.temp_file "clamp-phase8-kb" ".err" in
  let output =
    Unix.openfile output_path [ Unix.O_WRONLY; Unix.O_TRUNC; Unix.O_CLOEXEC ]
      0o600
  and errors =
    Unix.openfile error_path [ Unix.O_WRONLY; Unix.O_TRUNC; Unix.O_CLOEXEC ]
      0o600
  in
  let binary = kb_binary () in
  let environment =
    [| "PATH=/usr/bin:/bin"; "HOME=/nonexistent"; "LC_ALL=C"; "LANG=C" |]
  in
  let argv = Array.of_list (binary :: arguments) in
  let pid =
    Unix.create_process_env binary argv environment Unix.stdin output errors
  in
  Unix.close output;
  Unix.close errors;
  let _, status = Unix.waitpid [] pid in
  let stdout = read output_path and stderr = read error_path in
  Sys.remove output_path;
  Sys.remove error_path;
  status, stdout, stderr

let json_result expected_status expected_code arguments =
  let status, stdout, stderr = capture_kb arguments in
  Alcotest.(check bool) (expected_code ^ " status") true
    (status = Unix.WEXITED expected_status);
  Alcotest.(check string) (expected_code ^ " stderr") "" stderr;
  let json = Yojson.Safe.from_string stdout in
  Alcotest.(check string) (expected_code ^ " code") expected_code
    Yojson.Safe.Util.(json |> member "code" |> to_string);
  json

